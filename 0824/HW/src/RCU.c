void InitRCU(void)
{
    /* GD32F303 HD: HXTAL 8MHz → PREDV0(/2) → ×30 = 120MHz
     * 与 system_gd32f30x.c 的 system_clock_120m_hxtal() 一致。 */
    rcu_osci_on(RCU_HXTAL);
    while (rcu_osci_stab_wait(RCU_HXTAL) != SUCCESS) {}

    /* PREDV0 = 1: PLL 输入 = HXTAL/2 (4MHz)。旧 SPL 无独立函数, 直接配 CFG0。 */
    RCU_CFG0 |= RCU_CFG0_PREDV0;
    /* PLL 源 = HXTAL, 倍频 ×30 → 4MHz×30 = 120MHz */
    rcu_pll_config(RCU_PLLSRC_HXTAL_IRC48M, RCU_PLL_MUL30);

    rcu_osci_on(RCU_PLL_CK);
    while (rcu_osci_stab_wait(RCU_PLL_CK) != SUCCESS) {}

    /* 切系统时钟到 PLL, 等待切换完成 */
    rcu_system_clock_source_config(RCU_CKSYSSRC_PLL);
    while (rcu_system_clock_source_get() != RCU_SCSS_PLL) {}

    /* AHB = SYSCLK = 120MHz, APB1 = 60MHz, APB2 = 120MHz */
    rcu_ahb_clock_config(RCU_AHB_CKSYS_DIV1);
    rcu_apb1_clock_config(RCU_APB1_CKAHB_DIV2);
    rcu_apb2_clock_config(RCU_APB2_CKAHB_DIV1);

    SystemCoreClock = 120000000U;
}
